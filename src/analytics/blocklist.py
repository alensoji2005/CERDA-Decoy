"""Export attributed threat actors as firewall blocklists.

Writes files only; never touches the host firewall. Review, then apply yourself, e.g.:
    sudo nft -f cerda_blocklist.nft

Run: python -m src.analytics.blocklist [sessions.csv] [--min-sessions N] [--out-dir DIR]
"""
import argparse
import ipaddress
import os

import pandas as pd

NFT_TABLE = "cerda"
NFT_SET = "threat_actors"


def collect_blocklist(sessions: pd.DataFrame, min_sessions: int = 1) -> dict:
    """{threat_actor_id: sorted unique valid IPs} for actors seen in >= min_sessions sessions."""
    blocklist = {}
    for ta_id, group in sessions.groupby("threat_actor_id"):
        if len(group) < min_sessions:
            continue
        ips = set()
        for raw in group["source_ip"].astype(str):
            try:
                ip = ipaddress.ip_address(raw.strip())
            except ValueError:
                continue  # telemetry is attacker-influenced; never emit unvalidated text
            if ip.is_loopback or ip.is_unspecified:
                continue
            ips.add(ip)
        if ips:
            blocklist[ta_id] = [str(ip) for ip in sorted(ips, key=lambda i: (i.version, int(i)))]
    return blocklist


def render_nft(blocklist: dict) -> str:
    v4 = sorted({ip for ips in blocklist.values() for ip in ips if ":" not in ip})
    v6 = sorted({ip for ips in blocklist.values() for ip in ips if ":" in ip})
    lines = [
        "# Generated by CERDA. Review before applying: sudo nft -f <this file>",
        f"table inet {NFT_TABLE} {{",
        f"  set {NFT_SET}_v4 {{ type ipv4_addr; {'elements = { ' + ', '.join(v4) + ' }; ' if v4 else ''}}}",
        f"  set {NFT_SET}_v6 {{ type ipv6_addr; {'elements = { ' + ', '.join(v6) + ' }; ' if v6 else ''}}}",
        "  chain input {",
        "    type filter hook input priority 0; policy accept;",
        f"    ip saddr @{NFT_SET}_v4 drop",
        f"    ip6 saddr @{NFT_SET}_v6 drop",
        "  }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def render_plain(blocklist: dict) -> str:
    return "".join(f"{ip}  # {ta_id}\n" for ta_id, ips in blocklist.items() for ip in ips)


def export(sessions_path: str = "sessions.csv", out_dir: str = ".", min_sessions: int = 1) -> dict:
    blocklist = collect_blocklist(pd.read_csv(sessions_path), min_sessions)
    with open(os.path.join(out_dir, "cerda_blocklist.txt"), "w") as f:
        f.write(render_plain(blocklist))
    with open(os.path.join(out_dir, "cerda_blocklist.nft"), "w") as f:
        f.write(render_nft(blocklist))
    return blocklist


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("sessions", nargs="?", default="sessions.csv")
    parser.add_argument("--min-sessions", type=int, default=1, help="only block actors with at least N sessions")
    parser.add_argument("--out-dir", default=".")
    args = parser.parse_args()
    result = export(args.sessions, args.out_dir, args.min_sessions)
    print(f"Wrote {sum(map(len, result.values()))} IPs from {len(result)} threat actors "
          f"to {args.out_dir}/cerda_blocklist.{{txt,nft}}")
